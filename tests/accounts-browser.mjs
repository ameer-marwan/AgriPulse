import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const require=createRequire(import.meta.url);
let playwright;try{playwright=require('playwright');}catch{playwright=require('/opt/codex/runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');}
const browser=await playwright.chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const origin=process.env.FIELDSHIFT_PREVIEW||'http://127.0.0.1:4173';
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const portable=process.env.FIELDSHIFT_PORTABLE?await readFile(process.env.FIELDSHIFT_PORTABLE,'utf8'):null;
if(portable)await context.route(origin+'/',route=>route.fulfill({contentType:'text/html',body:portable}));
await context.addInitScript(()=>sessionStorage.setItem('fieldshift.intro.skip-auto','1'));
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
const address='qa-'+Date.now()+'@example.test',password='FieldShift testing password 47';
let cleanup=false;
try{
  await page.goto(origin+'/#/account',{waitUntil:'domcontentloaded'});
  await page.locator('[data-auth-tab="signup"]').click();
  await page.locator('#account-auth-form [name="name"]').fill('QA farmer');
  await page.locator('#account-auth-form [name="email"]').fill(address);
  await page.locator('#account-auth-form [name="password"]').fill(password);
  await page.locator('#account-submit').click();
  await page.locator('#account-profile-form').waitFor();cleanup=true;
  assert.equal(await page.locator('#view-account').isVisible(),true,'account route visible after signup');
  await page.waitForFunction(()=>document.querySelector('.account-sync-pill')?.textContent==='Cloud saved');
  await page.evaluate(()=>{location.hash='/settings';});
  await page.locator('#appearance').selectOption('dark');
  await page.waitForTimeout(1100);
  const remote=await page.evaluate(async()=>await(await fetch('/api/workspace')).json());
  assert.ok(remote.data,JSON.stringify(remote));
  assert.equal(JSON.parse(remote.data['fieldshift.preferences']).theme,'dark','preference is in real account database');
  const second=await browser.newContext();
  if(portable)await second.route(origin+'/',route=>route.fulfill({contentType:'text/html',body:portable}));
  await second.addInitScript(()=>sessionStorage.setItem('fieldshift.intro.skip-auto','1'));
  const other=await second.newPage();await other.goto(origin+'/#/account',{waitUntil:'domcontentloaded'});
  await other.locator('#account-auth-form [name="email"]').fill(address);
  await other.locator('#account-auth-form [name="password"]').fill('wrong password here');
  await other.locator('#account-submit').click();await other.locator('#account-form-error').filter({hasText:'incorrect'}).waitFor();
  await other.locator('#account-auth-form [name="password"]').fill(password);await other.locator('#account-submit').click();
  await other.locator('#account-profile-form').waitFor();
  assert.equal(await other.locator('#appearance').inputValue(),'dark','another browser login loads saved preferences');
  await other.locator('#account-profile-form [name="name"]').fill('QA profile updated');await other.locator('#account-profile-form button').click();
  await other.locator('#account-profile-form [name="name"]').filter({visible:true}).waitFor();
  await other.waitForFunction(()=>document.querySelector('#account-profile-form [name="name"]')?.value==='QA profile updated');
  await other.locator('#account-logout').click();await other.locator('#account-auth-form').waitFor();
  assert.equal(await other.locator('.account-sync-pill').textContent(),'Guest');
  assert.equal(await other.evaluate(async()=>(await fetch('/api/workspace')).status),401,'guest cannot read account workspace');
  await other.setViewportSize({width:390,height:844});
  assert.equal(await other.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile account page has no overflow');
  await second.close();
  assert.deepEqual(errors,[],'no startup errors');
  console.log('PASS: real signup, login errors, cross-session cloud saving, profile edit, logout, guest isolation, mobile layout.');
}finally{if(cleanup)await page.evaluate(async()=>await fetch('/api/account',{method:'DELETE',headers:{'content-type':'application/json'},body:JSON.stringify({confirm:'DELETE'})}));await browser.close();}
